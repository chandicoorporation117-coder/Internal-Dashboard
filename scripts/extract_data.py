"""Extract the weekly 20-head crime diary workbook into assets/data.js.

Usage:
    python scripts/extract_data.py "<path to week .xlsx>" "12 to 18 Oct 2026"

Reads the '20 Head - Dashboard' sheet (district rows x crime-head columns)
and writes a JS module the dashboard loads as window.CRIME_DATA.
"""
import json
import sys
from pathlib import Path

import openpyxl

SHEET = "20 Head - Dashboard"
HEADER_ROW = 5          # 1-based row holding "Sr. No. | Region | District | ..."
FIRST_HEAD_COL = 4      # 0-based index of the first crime-head column
OUT = Path(__file__).resolve().parent.parent / "assets" / "data.js"

# Short labels for the long PPC headings, in sheet column order.
SHORT_HEADS = [
    "Murder", "Dacoity", "Dacoity w/ Hurt", "Dacoity w/ Murder", "Dacoity w/ Rape",
    "Robbery", "Robbery w/ Hurt", "Robbery w/ Murder", "Robbery w/ Rape",
    "Snatching", "Child Sexual Abuse", "Rape/Sodomy (Minor)", "Vehicle Theft",
    "Burglary", "Acid Attack", "Rape", "Gang Rape", "Fatal Road Accidents",
    "Religious Cases", "Cattle Theft",
]


def main(xlsx_path: str, week_label: str) -> None:
    ws = openpyxl.load_workbook(xlsx_path, data_only=True)[SHEET]
    rows = list(ws.iter_rows(values_only=True))
    header = rows[HEADER_ROW - 1]
    full_heads = [str(h).strip() for h in header[FIRST_HEAD_COL:FIRST_HEAD_COL + len(SHORT_HEADS)]]

    districts, region = [], None
    for r in rows[HEADER_ROW:]:
        if not isinstance(r[0], int):
            continue  # skips the "Punjab Total" row and blanks
        region = (r[1] or region).strip()
        counts = [int(v or 0) for v in r[FIRST_HEAD_COL:FIRST_HEAD_COL + len(SHORT_HEADS)]]
        districts.append({
            "name": str(r[2]).strip(),
            "urdu": str(r[3]).strip(),
            "region": region,
            "counts": counts,
        })

    data = {
        "week": week_label,
        "source": Path(xlsx_path).name,
        "heads": SHORT_HEADS,
        "headsFull": full_heads,
        "districts": districts,
    }
    OUT.write_text(
        "// Generated by scripts/extract_data.py - do not edit by hand.\n"
        f"window.CRIME_DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    total = sum(sum(d["counts"]) for d in districts)
    print(f"Wrote {OUT} - {len(districts)} districts, {total} cases")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
